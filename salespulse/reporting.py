"""Report assembly and human-readable rendering."""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import UTC, date, datetime
from pathlib import Path
from typing import Any

import pandas as pd
from sqlalchemy import Engine

from salespulse.analytics import AnalyticsService, validate_date_range
from salespulse.ingestion import get_import_history, get_rejection_report
from salespulse.quality import quality_summary, run_quality_checks


@dataclass(slots=True)
class ReportBundle:
    date_from: str
    date_to: str
    sections: dict[str, pd.DataFrame]
    metadata: dict[str, Any] = field(default_factory=dict)

    @property
    def generated_at(self) -> str:
        return str(self.metadata.get("generated_at", ""))

    def section(self, name: str) -> pd.DataFrame:
        return self.sections[name]

    @property
    def title(self) -> str:
        return "SalesPulse Sales Performance Report"


def generate_report(
    engine: Engine,
    date_from: str | date,
    date_to: str | date,
    *,
    category: str | None = None,
    top_limit: int = 10,
    include_audit: bool = True,
) -> ReportBundle:
    start, end = validate_date_range(date_from, date_to)
    service = AnalyticsService(engine)
    sections: dict[str, pd.DataFrame] = {
        "Overview": service.overview_metrics(start, end),
        "Order Status": service.order_status_breakdown(start, end),
        "Daily Revenue": service.run_query("daily_revenue", date_from=start, date_to=end),
        "Monthly Revenue": service.run_query("monthly_revenue", date_from=start, date_to=end),
        "Monthly Revenue MoM": service.run_query(
            "monthly_revenue_mom", date_from=start, date_to=end
        ),
        "Product Performance": service.product_performance(start, end, category=category),
        "Category Performance": service.category_performance(start, end, category=category),
        "Top Products by Revenue": service.top_products(
            start, end, by="revenue", category=category, limit=top_limit
        ),
        "Customer New vs Returning": service.run_query(
            "new_vs_returning", date_from=start, date_to=end
        ),
        "Customer Summary": service.run_query(
            "customer_purchase_summary", date_from=start, date_to=end
        ),
        "Customer Frequency": service.run_query(
            "customer_frequency_distribution", date_from=start, date_to=end
        ),
        "Top Customers": service.run_query(
            "top_customers", date_from=start, date_to=end, limit=top_limit
        ),
        "Regional Performance": service.regional_performance(start, end),
        "Cancellation & Return Rates": service.cancellation_and_return_rates(start, end),
        "Monthly Rankings": service.monthly_rankings(start, end),
        "Data Quality": run_quality_checks(engine),
    }
    if include_audit:
        sections["Import History"] = get_import_history(engine, limit=50)
        sections["Rejected Records"] = get_rejection_report(engine)

    overview = sections["Overview"].iloc[0].to_dict() if not sections["Overview"].empty else {}
    quality = quality_summary(sections["Data Quality"])
    metadata: dict[str, Any] = {
        "title": "SalesPulse Sales Performance Report",
        "date_from": start,
        "date_to": end,
        "category_filter": category or "All categories",
        "top_limit": top_limit,
        "generated_at": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "data_source": "Synthetic demonstration data generated by SalesPulse",
        "synthetic_notice": (
            "All customers, products, and transactions are fictional and generated "
            "from a fixed random seed."
        ),
        "revenue_definition": (
            "Net revenue = recognised gross sales - item discounts - approved refunds "
            "for completed orders; returns are attributed to the original order date."
        ),
        "overview": overview,
        "quality_summary": quality,
        "sections": list(sections),
    }
    return ReportBundle(date_from=start, date_to=end, sections=sections, metadata=metadata)


def _format_metric_value(value: Any) -> str:
    if isinstance(value, float):
        return f"{value:,.2f}"
    if isinstance(value, int):
        return f"{value:,}"
    return str(value)


def format_overview(frame: pd.DataFrame) -> str:
    if frame.empty:
        return "No completed orders match the selected filters."
    row = frame.iloc[0]
    labels = {
        "completed_orders": "Completed orders",
        "unique_customers": "Unique purchasing customers",
        "units_sold": "Units sold",
        "gross_sales": "Gross sales (USD)",
        "discounts": "Discounts (USD)",
        "refunds": "Approved refunds (USD)",
        "net_revenue": "Net revenue (USD)",
        "average_order_value": "Average order value (USD)",
    }
    lines = ["KPI summary", "-" * 74]
    integer_columns = {"completed_orders", "unique_customers", "units_sold"}
    for column, label in labels.items():
        if column in row.index:
            value = int(row[column]) if column in integer_columns else row[column]
            lines.append(f"{label:<32} {_format_metric_value(value):>18}")
    return "\n".join(lines)


def format_report_text(bundle: ReportBundle, *, max_rows: int = 12) -> str:
    """A compact terminal view; all sections remain available for export."""
    lines = [
        "=" * 80,
        bundle.title,
        f"Period: {bundle.date_from} to {bundle.date_to} | "
        f"Category: {bundle.metadata.get('category_filter')}",
        "Synthetic demonstration data — not real business data",
        "=" * 80,
        "",
        format_overview(bundle.section("Overview")),
        "",
    ]
    display_sections = (
        "Order Status",
        "Monthly Revenue",
        "Top Products by Revenue",
        "Customer New vs Returning",
        "Regional Performance",
        "Cancellation & Return Rates",
    )
    for name in display_sections:
        frame = bundle.section(name)
        lines.extend([name, "-" * len(name)])
        if frame.empty:
            lines.append("No data matches the selected period.")
        else:
            lines.append(frame.head(max_rows).to_string(index=False))
            if len(frame) > max_rows:
                lines.append(f"... {len(frame) - max_rows} more rows available in exports")
        lines.append("")

    quality = bundle.section("Data Quality")
    summary = quality_summary(quality)
    failed = quality[quality["status"] == "fail"]
    lines.extend(
        [
            "Data quality",
            "------------",
            f"Checks: {summary['checks']} | Passed: {summary['passed']} | "
            f"Failed: {summary['failed']} | Critical failures: {summary['critical_failures']}",
        ]
    )
    if failed.empty:
        lines.append("All quality checks pass.")
    else:
        lines.append(failed[["check_name", "severity", "failures"]].to_string(index=False))
    lines.append("")
    return "\n".join(lines)


def write_markdown_report(bundle: ReportBundle, output_path: str | Path) -> Path:
    """Write a portfolio-friendly Markdown report from the actual SQL results."""
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    quality = quality_summary(bundle.section("Data Quality"))
    lines = [
        f"# {bundle.title}",
        "",
        f"**Period:** {bundle.date_from} to {bundle.date_to}  ",
        f"**Category filter:** {bundle.metadata.get('category_filter')}  ",
        f"**Generated:** {bundle.generated_at}  ",
        "**Data:** Synthetic demonstration data, fixed random seed",
        "",
        "> This report is generated from the SalesPulse SQLite database. "
        "It does not describe real business data.",
        "",
        "## KPI summary",
        "",
    ]
    overview = bundle.section("Overview")
    if overview.empty:
        lines.append("_No completed orders match the selected filters._")
    else:
        row = overview.iloc[0]
        lines.extend(
            [
                "| Metric | Value |",
                "|---|---:|",
                f"| Completed orders | {int(row['completed_orders']):,} |",
                f"| Net revenue | ${row['net_revenue']:,.2f} |",
                f"| Gross sales | ${row['gross_sales']:,.2f} |",
                f"| Discounts | ${row['discounts']:,.2f} |",
                f"| Refunds | ${row['refunds']:,.2f} |",
                f"| Average order value | ${row['average_order_value']:,.2f} |",
                f"| Unique customers | {int(row['unique_customers']):,} |",
            ]
        )
    lines.extend(["", "## Monthly revenue", ""])
    monthly = bundle.section("Monthly Revenue")
    if monthly.empty:
        lines.append("_No monthly data._")
    else:
        lines.append(monthly.to_markdown(index=False, floatfmt=",.2f"))
    lines.extend(["", "## Top products by net revenue", ""])
    products = bundle.section("Top Products by Revenue")
    if products.empty:
        lines.append("_No product data._")
    else:
        lines.append(products.to_markdown(index=False, floatfmt=",.2f"))
    lines.extend(["", "## Customer mix", ""])
    customers = bundle.section("Customer New vs Returning")
    if customers.empty:
        lines.append("_No customer data._")
    else:
        lines.append(customers.to_markdown(index=False, floatfmt=",.2f"))
    lines.extend(["", "## Regional performance", ""])
    regional = bundle.section("Regional Performance")
    if regional.empty:
        lines.append("_No regional data._")
    else:
        lines.append(regional.to_markdown(index=False, floatfmt=",.2f"))
    lines.extend(
        [
            "",
            "## Data quality",
            "",
            f"**Status:** {'PASS' if quality['status'] == 'pass' else 'FAIL'} — "
            f"{quality['passed']} of {quality['checks']} checks passed "
            f"({quality['critical_failures']} critical failures, "
            f"{quality['warning_failures']} warnings).",
            "",
        ]
    )
    failed = bundle.section("Data Quality")
    failed = failed[failed["status"] == "fail"]
    if not failed.empty:
        lines.append(
            failed[["check_name", "severity", "failures", "detail"]].to_markdown(index=False)
        )
    lines.extend(
        [
            "",
            "## Definitions",
            "",
            str(bundle.metadata["revenue_definition"]),
            "",
            "Returns are attributed to the original order date. Pending and cancelled "
            "orders are excluded from recognised revenue but remain visible in order-volume "
            "and cancellation metrics.",
            "",
        ]
    )
    path.write_text("\n".join(lines), encoding="utf-8")
    return path
